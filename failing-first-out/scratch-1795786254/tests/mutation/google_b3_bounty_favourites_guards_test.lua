-- guards Wuber/Net/Bounty.lua:310 (MAX_SENDERS eviction keeps other senders at oldPlace)
test("mutation b3 bounty MAX_SENDERS eviction preserves other pledges at oldPlace", function()
	local w = T.newWorld()
	local d = T.driver(w, T.ANITA)
	T.settle(w)
	-- Oldest sender (s1) and second sender (s2) both pledge for Gadgetzan; 198 others pledge for Crossroads
	w:inject("Sender One", "W~1~Gadgetzan~5000~H~30", "CHANNEL", d)
	w:advance(0.1)
	w:inject("Sender Two", "W~1~Gadgetzan~6000~H~30", "CHANNEL", d)
	for i = 3, 200 do
		w:advance(0.1)
		w:inject("Sender " .. i, "W~1~Crossroads~5000~H~30", "CHANNEL", d)
	end
	w:advance(0.1)
	w:inject("Sender Twohundredone", "W~1~Everlook~5000~H~30", "CHANNEL", d)
	ok(d.W.bounties["Gadgetzan"] ~= nil, "Gadgetzan still has Sender Two")
	ok(d.W.bounties["Gadgetzan"]["sender two"] ~= nil, "Sender Two was not wiped when Sender One was evicted")
	T.clean(w)
end)

-- guards Wuber/Net/Favourites.lua:86 (flushToasts suppresses WATCH_HIT when fav was recently toasted)
test("mutation b3 favs favourite at watched place fires FAV_ONLINE only, not WATCH_HIT", function()
	local w = T.newWorld()
	local r = T.rider(w, T.TESTCHAR)
	local d = T.driver(w, T.BOB, { spot = "Orgrimmar" })
	T.settle(w)
	local favs, watches = 0, 0
	r.W.Listen("FAV_ONLINE", function() favs = favs + 1 end)
	r.W.Listen("WATCH_HIT", function() watches = watches + 1 end)
	r.W.ToggleFav(T.BOB)
	T.goOnline(d, { price = 5000 })
	w:advance(6)
	eq(favs, 1, "FAV_ONLINE fired once")
	-- Now watch Orgrimmar and Bob re-opens within 10 minutes: seen[key] is nil, favToasted suppresses WATCH_HIT
	r.W.ToggleWatch("Orgrimmar")
	d.W.Driver.SetOnline(false)
	w:advance(2)
	T.goOnline(d, { price = 5000 })
	w:advance(12)
	eq(watches, 0, "WATCH_HIT suppressed because recently toasted as favourite")
	T.clean(w)
end)

