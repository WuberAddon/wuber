-- guards Wuber/Net/Bounty.lua:122 (sendNow caps whisper copies at BK.WHISPERS = 6)
test("mutation b3 bounty sendNow caps whisper copies at 6 drivers", function()
	local w = T.newWorld()
	local r = T.rider(w, T.TESTCHAR)
	T.settle(w)
	local base = r.W.Mod("Net.Base")
	local now = base.now()
	for i = 1, 7 do
		local k = "driver" .. i
		base.fb.qAddr[k] = "Driver" .. i
		base.fb.qAt[k] = now
	end
	eq(r.W.Bounty.Pin("Gadgetzan", 5000), true, "bounty pinned")
	w:advance(15)
	local whispers = T.msgs(w, "W", T.TESTCHAR, "WHISPER")
	eq(#whispers, 6, "at most 6 whisper copies sent")
	T.clean(w)
end)

