local T = ...
local test, eq, ok = T.test, T.eq, T.ok
local ANITA, TESTCHAR = T.ANITA, T.TESTCHAR

test("r33 o2 AUD-42: a hidden driver who signs off must not come back as online when the rider shows hidden drivers", function()
	local w = T.newWorld()
	local d = T.driver(w, ANITA, { spot = "Ratchet" })
	local r = T.rider(w, TESTCHAR, { spot = "Ratchet" })
	T.settle(w)
	T.goOnline(d)
	w:advance(5)
	ok(r.W.drivers["anita lift"] ~= nil, "control: the rider sees Anita driving")
	r.W.HideDriver("anita lift", true)
	ok(r.W.drivers["anita lift"] == nil, "control: hidden, she is not listed")
	T.goOffline(d)
	w:advance(5)
	local sentX = #T.msgs(w, "X", ANITA)
	ok(sentX > 0, "control: Anita sent her sign-off X")
	r.W.ShowAllDrivers()
	w:advance(1)
	ok(r.W.drivers["anita lift"] == nil, "Anita signed off, yet after Show all hidden drivers she is listed as driving again")
	T.clean(w)
end)

test("r33 o2 AUD-42: control: an unhidden driver who signs off leaves the list", function()
	local w = T.newWorld()
	local d = T.driver(w, ANITA, { spot = "Ratchet" })
	local r = T.rider(w, TESTCHAR, { spot = "Ratchet" })
	T.settle(w)
	T.goOnline(d)
	w:advance(5)
	T.goOffline(d)
	w:advance(5)
	ok(r.W.drivers["anita lift"] == nil, "she is gone")
	T.clean(w)
end)
