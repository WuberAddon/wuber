-- Wuber 2.4, simple rider: Simple mode hides power-user controls on rider screens, empty OpenMap line and single gold raid button. Loaded by tests/run.lua with its helper table T.
local T = ...
local test, eq, ok = T.test, T.eq, T.ok

-- helper: three completed rides with one driver to a place (for usual, habit, tier and Wrapped)
local function seedRides(r, driverName, dest, extraMonths)
	local key = r.W.Key(driverName)
	local nowTs = (type(r.env.time) == "function" and r.env.time()) or 1763600000
	local list = {
		{ dest = dest, driver = driverName, driverKey = key, at = nowTs - 7200, price = 5000, saved = 540, stars = 5 },
		{ dest = dest, driver = driverName, driverKey = key, at = nowTs - 86400 - 3600, price = 5000, saved = 540, stars = 5 },
		{ dest = dest, driver = driverName, driverKey = key, at = nowTs - 2 * 86400 - 3600, price = 5000, saved = 540, stars = 5 },
	}
	if extraMonths then
		for i = 1, 3 do
			list[#list + 1] = { dest = dest, driver = driverName, driverKey = key, at = nowTs - 35 * 86400 - i * 3600, price = 5000, saved = 540, stars = 5 }
			list[#list + 1] = { dest = dest, driver = driverName, driverKey = key, at = nowTs - 65 * 86400 - i * 3600, price = 5000, saved = 540, stars = 5 }
		end
	end
	r.W.db.rides = list
	r.W.db.totals = nil -- tiers, habits and Wrapped count from the trips again
end

-- find the driver row Button frame from a visible text inside it
local function driverRow(r, text)
	local list = r:findText(text, false, true)
	local f = list[1] and list[1]:GetParent() or nil
	while f and not f.key do
		f = f.GetParent and f:GetParent() or nil
	end
	return f
end

-- a real ride with the driver, run as far as the stage: "requested", "ingroup", "arrived" or "done" (paid by trade)
local function rideTo(w, d, r, stage)
	local ride = r.W.RequestRide(r.W.Key(d.player.name))
	if stage == "requested" then
		w:advance(0.1) -- before the driver has answered
		return ride
	end
	w:advance(1)
	d.W.AcceptRequest(d.W.incoming[1].id, 5)
	w:advance(2)
	if stage == "ingroup" then return ride end
	r.W.UI.Toggle(true)
	w:advance(2.5)
	w:summon(d, r.player.name)
	w:advance(1)
	r:clickText("Accept summon")
	w:advance(3)
	if stage == "arrived" then return ride end
	w:openTrade(d, r)
	w:advance(0.5)
	w:tradeMoney(r, 5000)
	w:tradeAccept(d)
	w:tradeAccept(r)
	w:advance(1)
	return ride
end

test("v24 simple rider: 1 right-click menu disabled and tooltip shortened in Simple, heart works", function()
	local w = T.newWorld()
	local d = T.driver(w, T.ANITA)
	local r = T.rider(w, T.TESTCHAR, { simple = true })
	T.settle(w)
	T.goOnline(d, { price = 5000 })
	w:advance(2)
	r.W.UI.Toggle(true)
	w:advance(1)
	local row = driverRow(r, "Anita")
	ok(row ~= nil, "driver row found")
	local bodySimple = row.wuberTip.text(row)
	ok(bodySimple:find("Click to book.", 1, true) ~= nil, "Simple tooltip ends with Click to book.")
	ok(bodySimple:find("Right-click to favourite or hide.", 1, true) == nil, "Simple tooltip omits right-click hint")
	row:Click("RightButton")
	w:advance(0.5)
	eq(#r:findText("Hide this driver", false, true), 0, "right-click menu does not open in Simple")
	row.heart:Click("LeftButton")
	w:advance(0.5)
	ok(r.W.UI.IsFav(row.key), "heart favourite still works in Simple")
	r.W.SetAdvanced(true)
	w:advance(0.5)
	local bodyAdv = row.wuberTip.text(row)
	ok(bodyAdv:find("Right-click to favourite or hide.", 1, true) ~= nil, "Advanced tooltip includes right-click hint")
	row:Click("RightButton")
	w:advance(0.5)
	ok(#r:findText("Hide this driver", false, true) > 0, "right-click menu opens in Advanced")
	T.clean(w)
end)

