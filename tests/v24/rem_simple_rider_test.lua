test("v24 simple rider: 7 raid card uses the screen's one main button even with usual and drivers listed", function()
	local w = T.newWorld()
	local d = T.driver(w, T.ANITA)
	local r = T.rider(w, T.TESTCHAR, { simple = true, spot = "Orgrimmar" })
	seedRides(r, d.player.name, "Ratchet")
	-- (fga f2) the first click lands while the splash is up: its press ends the splash, and the first-open guide would
	-- come over Home 0.6 s later and take the click on Your usual (by design); this test is about the raid button
	r.W.db.coach = true
	T.settle(w)
	T.goOnline(d, { price = 5000 })
	w:advance(2)
	local asked = 0
	local raidInfo = { runner = T.BOB, place = "Molten Core", summoners = { T.BOB }, queued = false }
	r.W.UI.RaidHere = function() return raidInfo end
	r.W.Drive.RaidAsk = function()
		asked = asked + 1
		raidInfo.queued = true
		return true
	end
	r.W.UI.Toggle(true)
	w:advance(1)
	ok(#r:findText("Get summoned to Molten Core", false, true) > 0, "raid card shown")
	ok(#r:findText("Your usual", false, true) > 0, "Your usual card keeps its place")
	eq(#r:findText("Request a summon", false, true), 1, "exactly one Request a summon button")
	eq(#r:findText("Ride again", false, true), 0, "no second Ride again main button while raid button shows")
	-- the scrolled list is clipped in the game but the fake game still hit-tests a row behind the button: click the button itself
	r:click(r:clickable(r:findText("Request a summon", false, true)[1]))
	w:advance(0.5)
	eq(asked, 1, "clicking main button invokes RaidAsk")
	ok(#r:findText("You're on the summon list", false, true) > 0, "raid card shows queued text")
	eq(#r:findText("Request a summon", false, true), 0, "raid main button gone once queued")
	ok(#r:findText("Ride again · Ratchet · 50s", false, true) > 0, "main button falls back to Ride again when queued")
	raidInfo.queued = false
	r.W.UI.Refresh(true)
	w:advance(0.5)
	r:clickText("Your usual")
	w:advance(0.5)
	ok(#r:findText("Summon to Ratchet", false, true) > 0, "clicking Your usual card opens Confirm")
	T.clean(w)
end)

