-- Wuber 2.4, Simple and Advanced: the one saved switch (W.Advanced, W.SetAdvanced, /wuber advanced) and how a
-- player starts. Loaded by tests/run.lua with its helper table T.
local T = ...
local test, eq, ok = T.test, T.eq, T.ok

test("v24 simple: a new player starts in Simple, with nothing to be told", function()
	local w = T.newWorld()
	local r = T.rider(w, T.TESTCHAR, { simple = true })
	T.settle(w)
	eq(r.W.Advanced(), false, "a first install is Simple")
	eq(r.env.WuberDB.advanced, false, "saved as off")
	eq(r.env.WuberDB.simpleNote, nil, "a new player has no note waiting")
	T.clean(w)
end)

test("v24 simple: a player with saved data from before starts in Simple, keeps every value and has the note waiting", function()
	local w = T.newWorld()
	local r = T.rider(w, T.TESTCHAR, { simple = true, saved = { Wuber = { sound = false, fx = "light", timeValue = 250000 } } })
	T.settle(w)
	local db = r.env.WuberDB
	eq(r.W.Advanced(), false, "Simple at the relaunch")
	eq(db.simpleNote, true, "the one line is waiting")
	eq(db.sound, false, "sound kept")
	eq(db.fx, "light", "effects kept")
	eq(db.timeValue, 250000, "my time is worth kept")
	T.clean(w)
end)

test("v24 simple: /wuber advanced switches the mode, says so, changes no other value and survives a reload", function()
	local w = T.newWorld()
	local r = T.rider(w, T.TESTCHAR, { simple = true, saved = { Wuber = { sound = false, autoLeave = false } } })
	T.settle(w)
	local heard = 0
	r.W.Listen("SETTINGS", function(key) if key == "advanced" then heard = heard + 1 end end)
	r:slash("/wuber advanced")
	eq(r.W.Advanced(), true, "Advanced after the command")
	ok(r:said("Advanced mode: on%."), "the chat line says on")
	eq(heard, 1, "SETTINGS advanced fired once")
	eq(r.env.WuberDB.sound, false, "sound untouched")
	eq(r.env.WuberDB.autoLeave, false, "auto leave untouched")
	r = w:reload(r)
	T.settle(w)
	eq(r.W.Advanced(), true, "still Advanced after a reload")
	r:slash("/wuber advanced")
	eq(r.W.Advanced(), false, "and off again")
	ok(r:said("Advanced mode: off%."), "the chat line says off")
	r.W.SetAdvanced(false)
	eq(r.W.Advanced(), false, "setting the same value changes nothing")
	T.clean(w)
end)

test("v24 simple: the tests' own windows start in Advanced unless a test asks for Simple", function()
	local w = T.newWorld()
	local r = T.rider(w, T.TESTCHAR)
	local d = T.driver(w, T.ANITA, { saved = { Wuber = { sound = false } } })
	T.settle(w)
	eq(r.W.Advanced(), true, "a rider's window")
	eq(d.W.Advanced(), true, "a driver's window with its own saved data")
	eq(d.env.WuberDB.simpleNote, nil, "no note in Advanced")
	T.clean(w)
end)
