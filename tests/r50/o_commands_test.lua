local T = ...
local test = T.test
local function printed(W) local out = {} W.Print = function(t) out[#out+1] = tostring(t) end return out end
test("r50 O: drive scale refuses out-of-range and still takes percent and in-range", function()
	local w = T.newWorld()
	local a = T.driver(w, T.ANITA, { spot = "Undercity" })
	w:advance(15)
	local out = printed(a.W)
	local DR = a.W.Drive
	DR.Command("scale 1.5"); DR.Command("scale 4")
	assert(DR.Scale() == 1.5, "4 changed the size: " .. DR.Scale())
	DR.Command("scale 0.2")
	assert(DR.Scale() == 1.5, "0.2 changed the size")
	assert(table.concat(out, " "):find("0.5 to 3", 1, true), "no message")
	DR.Command("scale 200"); assert(math.abs(DR.Scale() - 2) < 0.01, "200 percent: " .. DR.Scale())
	DR.Command("scale 2.5"); assert(math.abs(DR.Scale() - 2.5) < 0.01, "2.5: " .. DR.Scale())
	T.clean(w)
end)
test("r50 O: drive unblock with no name prints its usage", function()
	local w = T.newWorld()
	local a = T.driver(w, T.ANITA, { spot = "Undercity" })
	w:advance(15)
	local out = printed(a.W)
	a.W.Drive.Command("unblock")
	assert(table.concat(out, " "):find("unblock <name>", 1, true), "no usage: " .. table.concat(out, "|"))
	T.clean(w)
end)
