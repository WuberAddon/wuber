-- Was in tests/run.lua. Not loaded by the suite; kept for the record. It needed the old addon's own code (Ritual Rides 1.4.1), which is not in this repository.

test("Ritual Rides: price below the beacon -> N price; blocked rider -> N blocked", function()
	rrNeeded()
	local w = newWorld()
	local cs = rrTeam(w)
	local r = rider(w)
	settle(w, 20)
	w:inject(TESTCHAR, "R~1~ABCDEF~Ratchet~100", "WHISPER", cs[1])
	w:advance(2)
	local N = msgs(w, "N", ANA)
	eq(#N, 1, "N for a low price")
	eq(fields(N[1])[4], "price")
	cs[1]:slash("/rr block Bob Stone")
	w:addBot(BOB)
	w:inject(BOB, "R~1~GHIJKL~Ratchet~50000", "WHISPER", cs[1])
	w:advance(2)
	N = msgs(w, "N", ANA)
	eq(#N, 2, "N for a blocked rider")
	eq(fields(N[2])[4], "blocked")
	clean(w)
end)
