local T = ...
local H, test, eq, ok = T.H, T.test, T.eq, T.ok

test("r47 f4: opening Crew over the console leaves the invisible Advertise overlay clickable", function()
	local w = T.newWorld()
	local a = T.driver(w, T.ANITA, { spot = "Ratchet" })
	T.goOnline(a)
	w:advance(20)
	local W = a.W
	T.openDrive(a)
	W.UI.ShowDrive("console")
	w:advance(2)
	local adv = a.env.WuberAdvertButton
	ok(adv, "the advert overlay exists")
	ok(adv:IsShown(), "control: on the console the Advertise overlay lies over its pill")
	W.UI.ShowDrive("crew")
	w:advance(0.1)
	eq(W.Driver.CurrentScreen(), "crew", "the Crew screen is open")
	ok(not adv:IsShown(), "the Crew screen is open but the invisible Advertise overlay still lies over it (shown, level " .. tostring(adv:GetFrameLevel()) .. ") for up to a second: a tap there posts an advert instead of hitting Crew")
	w:advance(1.2)
	ok(not adv:IsShown(), "control: a second later the overlay has gone")
	T.clean(w)
end)
test("r47 f4: closing a bottom sheet leaves the Advertise pill without its secure overlay for a moment", function()
	local w = T.newWorld()
	local a = T.driver(w, T.ANITA, { spot = "Ratchet" })
	T.goOnline(a)
	w:advance(20)
	local W = a.W
	T.openDrive(a)
	W.UI.ShowDrive("console")
	w:advance(2)
	local adv = a.env.WuberAdvertButton
	ok(adv and adv:IsShown(), "control: on the console the Advertise overlay lies over its pill")
	ok(W.Driver.ShowSheet("sheet"), "the price sheet opens")
	w:advance(1.5)
	ok(W.Driver.SheetOpen(), "the sheet is open")
	ok(not adv:IsShown(), "control: while the sheet is open the overlay is off the pill")
	W.Driver.ui.sheets.sheet.frame:Close()
	w:advance(0.1)
	ok(not W.Driver.SheetOpen(), "the sheet closed")
	ok(adv:IsShown(), "the sheet is closed and the Advertise pill is back, but its secure overlay is not: a tap on Advertise right now finds no advert macro (it comes back at the next 1 s tick)")
	T.clean(w)
end)