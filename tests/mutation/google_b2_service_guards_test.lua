test("mutation b2 service: TeamShards lists crew Warlock peers in alphabetical order", function()
	local w = T.newWorld()
	local a = T.driver(w, T.ANA, { spot = "Orgrimmar" })
	T.settle(w)
	a.W.Drive.peers["bob lock"] = { name = "Bob Lock", role = "L", shards = 5, at = a.env.GetTime() }
	a.W.Drive.peers["cal lock"] = { name = "Cal Lock", role = "L", shards = 3, at = a.env.GetTime() }
	local total, line = a.W.Drive.TeamShards()
	local bobPos = line:find("Bob 5", 1, true)
	local calPos = line:find("Cal 3", 1, true)
	ok(bobPos and calPos and bobPos < calPos, "peers appear in alphabetical order: " .. tostring(line))
	ok(total >= 8, "total includes both peers' shards")
	T.clean(w)
end)

