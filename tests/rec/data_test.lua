-- Tests of tools/rec/gen-data.lua (the data file of the developer-only recorder addon WuberRec): the
-- generator's output for this tree is the Data.lua on disk, names the game forbids are not in it, and the
-- lists hold what the recorder needs. Loaded by tests/run.lua with its helper table T.
local T = ...
local eq, ok = T.eq, T.ok

local ROOT = T.dir .. "/.."
local GEN = assert(loadfile(ROOT .. "/tools/rec/gen-data.lua"))("--lib")

local function readAll(path)
	local f = io.open(path, "rb")
	if not f then return nil end
	local s = f:read("*a")
	f:close()
	return s
end

local function folder()
	local d = os.getenv("WUBER_REC_DIR")
	if d and d ~= "" then return (d:gsub("\\", "/"):gsub("/+$", "")) end
	return "WuberRec"
end

-- The generator takes about 3 s. It runs on the first test of this file that runs, not when the file loads,
-- because every tests/run.lua process loads every test file (a filtered run, a quick-check chunk, a mutant).
local text, data, made
local function test(name, fn)
	return T.test(name, function(...)
		if not made then
			made = true
			text, data = GEN.generate(ROOT)
		end
		return fn(...)
	end)
end

local function has(list, name)
	for _, v in ipairs(list) do if v == name then return true end end
	return false
end

test("tools/rec/gen-data.lua: the generator reads this tree", function()
	ok(text, "generate failed: " .. tostring(data))
	ok(text:find("GENERATED by tools/rec/gen-data.lua", 1, true), "header")
	ok(text:find('R.DATA_FROM = "Wuber ', 1, true), "version line")
	ok(not text:find("%d%d%d%d%-%d%d%-%d%d") and not text:find("%f[%x]%x%x%x%x%x%x%x%x*%f[^%x]%s*$"), "no date, no hash")
	eq(GEN.generate(ROOT), text, "deterministic")
end)

test("tools/rec/gen-data.lua: Data.lua on disk is what the generator makes", function()
	local path = folder() .. "/Data.lua"
	local disk = readAll(path)
	if not disk then
		if not readAll(folder() .. "/WuberRec.toc") then return end -- no recorder folder here: nothing to compare
		ok(false, path .. " is missing: run tools/rec/gen-data.lua")
	end
	-- Data.lua belongs to ONE Wuber version (its R.DATA_FROM line). A branch with another Wuber version
	-- (the next line of work) is not what the addon on this PC was made for: nothing to compare then.
	local mine, theirs = text:match('R%.DATA_FROM = "([^"]*)"'), disk:match('R%.DATA_FROM = "([^"]*)"')
	if mine ~= theirs then return end
	ok(disk == text, path .. " is stale: run lua5.1 tools/rec/gen-data.lua")
end)

test("tools/rec/gen-data.lua: no name the game forbids is in Data.lua", function()
	local list = assert(loadfile(ROOT .. "/tools/forbidden.lua"))()
	ok(#list > 0, "the forbidden list")
	for _, f in ipairs(list) do
		ok(not text:find("%f[%w_]" .. f.name .. "%f[^%w_]"), f.name .. " is in the generated data")
	end
	local disk = readAll(folder() .. "/Data.lua")
	if disk then
		for _, f in ipairs(list) do
			ok(not disk:find("%f[%w_]" .. f.name .. "%f[^%w_]"), f.name .. " is in " .. folder() .. "/Data.lua")
		end
	end
end)

test("tools/rec/gen-data.lua: a forbidden event in Wuber makes it fail", function()
	local out, err = GEN.generate(ROOT, { forbidden = { { name = "PLAYER_LOGIN", kind = "event", why = "test" } } })
	eq(out, nil)
	ok(tostring(err):find("PLAYER_LOGIN", 1, true), tostring(err))
	local out2 = GEN.generate(ROOT, { forbidden = { { name = "GetTime", kind = "api", path = { "GetTime" }, why = "test" } } })
	eq(out2, nil, "an API name too")
end)

test("tools/rec/gen-data.lua: events, prefixes, frames, maps", function()
	ok(#data.events >= 50, "events: " .. #data.events)
	for _, e in ipairs({ "PLAYER_LOGIN", "TAXIMAP_OPENED", "CONFIRM_SUMMON", "CHAT_MSG_ADDON", "TRADE_ACCEPT_UPDATE",
		"NAME_PLATE_UNIT_ADDED", "CHAT_MSG_RAID_LEADER", "CLUB_ADDED" }) do
		ok(has(data.events, e), "event " .. e)
	end
	ok(not has(data.events, "TRADE_ACCEPT"), "a name only in a comment or not an event is not listed")
	ok(has(data.prefixes, "WUBER") and has(data.prefixes, "WUBERT"), "prefixes")
	eq(#data.prefixes, 2)
	ok(has(data.fires, "ADVERT") and has(data.fires, "DRIVE_CREW"), "fires, also from a loop")
	ok(has(data.gs, "ERR_ALREADY_IN_GROUP_S") and has(data.gs, "ERR_TRADE_COMPLETE"), "global strings")
	ok(has(data.gameFrames, "TaxiFrame") and has(data.gameFrames, "ChatFrame1") and has(data.gameFrames, "MainMenuBar")
		and has(data.gameFrames, "DaylightUIBar1"), "game frames, the HUD ones from Toasts.lua")
	ok(has(data.api, "C_Map.GetBestMapForUnit") and has(data.api, "C_Map") and has(data.api, "TaxiNodePosition")
		and has(data.api, "C_ChatInfo.SendAddonMessage"), "api")
	local maps = table.concat(data.maps, ",")
	eq(maps, "947,1414,1415")
	local frames = {}
	for _, f in ipairs(data.frames) do frames[f[1]] = f[2] or false end
	ok(frames.WuberFrame ~= nil and frames.WuberFrame == false, "WuberFrame is plain")
	ok(frames.WuberDriveButton == true, "WuberDriveButton is secure")
	local src = readAll(ROOT .. "/Wuber/UI/Secure.lua")
	local n = 0
	for name in src:gmatch("makeSecure%(%s*\"([%w_]+)\"") do
		n = n + 1
		ok(frames[name] == true, name .. " must be flagged secure")
	end
	for name in src:gmatch("advertButton%(%s*\"([%w_]+)\"") do
		n = n + 1
		ok(frames[name] == true, name .. " must be flagged secure")
	end
	ok(n >= 5, "Secure.lua buttons found: " .. n)
end)
