"""Writes tools/preview/fontmetrics.lua: each shipped font's glyph advances (per 1.0 of font size,
unhinted, as the game's vector text draws them), its ascent/descent, and kerning pairs, for the
fake game's text measuring in preview mode (tests/harness.lua H.textMetrics) and for render.py.
  python tools/preview/fontmetrics.py            (run again only when a font file changes)
  python tools/preview/fontmetrics.py --tokens   also prints the width table of Wuber/Theme/Tokens.lua (local
      INTER_W: characters 32..126 in thousandths of the font size, per weight) and ACCENT_W (the mean width of
      the small accented Latin-1 letters U+00DF..00FF, mean of the three weights): paste them there, never type them by hand"""
import os, sys
from PIL import ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.join(HERE, "..", "..", "Wuber", "Media", "fonts")
RANGES = [(32, 127), (160, 384), (0x2010, 0x2070), (0x2190, 0x21FF), (0x2600, 0x2800), (0x00D7, 0x00D8)]


def one(path):
    big = 2048  # large enough that the advances are the font's own (unhinted) numbers
    f = ImageFont.truetype(path, big, layout_engine=ImageFont.Layout.BASIC)
    adv = {}
    for lo, hi in RANGES:
        for cp in range(lo, hi):
            ch = chr(cp)
            try:
                mask = f.getmask(ch)
            except Exception:
                continue
            # a glyph the font lacks draws its .notdef box: skip those (not space-like ones)
            if cp != 32 and cp != 160 and f.getbbox(ch) == f.getbbox("\uffff"):
                continue
            adv[cp] = f.getlength(ch) / big
    asc, desc = f.getmetrics()
    return {"adv": adv, "asc": asc / big, "desc": desc / big, "gap": 0.0, "fallback": adv.get(ord("n"), 0.55)}


# the game's own fonts are not on disk (packed in its data): stand-ins with a width factor
GAME = {"frizqt__.ttf": (__import__("os").path.join(__import__("os").environ.get("WINDIR", ""), "Fonts", "georgia.ttf"), 0.96), "arialn.ttf": (__import__("os").path.join(__import__("os").environ.get("WINDIR", ""), "Fonts", "arial.ttf"), 0.82)}


def main():
    out = ["-- generated by tools/preview/fontmetrics.py: do not edit", "return {"]
    todo = [(n.lower(), os.path.join(FONTS, n), 1.0) for n in sorted(os.listdir(FONTS)) if n.lower().endswith(".ttf")]
    for n, (p, k) in GAME.items():
        if os.path.exists(p):
            todo.append((n, p, k))
    for name, path, k in todo:
        m = one(path)
        if k != 1.0:
            m["adv"] = {cp: a * k for cp, a in m["adv"].items()}
            m["fallback"] *= k
        out.append('\t["%s"] = { asc = %.4f, desc = %.4f, gap = %.4f, fallback = %.4f, adv = {' % (name, m["asc"], m["desc"], m["gap"], m["fallback"]))
        row = []
        for cp in sorted(m["adv"]):
            row.append("[%d]=%.4f" % (cp, m["adv"][cp]))
            if len(row) == 12:
                out.append("\t\t" + ", ".join(row) + ",")
                row = []
        if row:
            out.append("\t\t" + ", ".join(row) + ",")
        out.append("\t} },")
    out.append("}")
    open(os.path.join(HERE, "fontmetrics.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("fontmetrics.lua written")


def tokens():
    """The lines of Tokens.lua's width table, from the same measure as fontmetrics.lua."""
    half = lambda x: int(x * 1000 + 0.5)
    means = []
    print("local INTER_W = {")
    for weight in ("Regular", "Medium", "Bold"):
        adv = one(os.path.join(FONTS, "Inter-%s.ttf" % weight))["adv"]
        print("\t%s = { %s }," % (weight.lower(), ", ".join(str(half(adv[cp])) for cp in range(32, 127))))
        letters = [adv[cp] for cp in range(0xDF, 0x100) if cp != 0xF7]
        means.append(sum(letters) / len(letters))
    print("}")
    print("local ACCENT_W = %d -- per weight: %s" % (half(sum(means) / 3), ", ".join(str(half(m)) for m in means)))


if __name__ == "__main__":
    if "--tokens" in sys.argv:
        tokens()
    main()
