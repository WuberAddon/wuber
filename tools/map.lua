-- tools/map.lua (REFACTOR-MAP 6.3): writes ARCHITECTURE.md from the TOC and the module headers.
--   lua5.1 tools/map.lua            print ARCHITECTURE.md to stdout
--   lua5.1 tools/map.lua --write    write it to ARCHITECTURE.md
--   lua5.1 tools/map.lua --check    exit 1 if ARCHITECTURE.md is out of date
-- The hand-written intro lives in tools/architecture-intro.md (edit that, then regenerate).
-- Static: no addon code runs. Output is deterministic (TOC order, no dates).
-- loadfile("tools/map.lua")("--lib") returns { build = function(root) -> text, modules = function(root) -> list }.

local M = {}

local function readFile(path)
	local f = io.open(path, "rb")
	if not f then return nil end
	local s = f:read("*a")
	f:close()
	return s
end

local function tocFiles(root)
	local toc = assert(readFile(root .. "/Wuber/Wuber.toc"), "cannot read Wuber/Wuber.toc")
	local out = {}
	for line in toc:gmatch("[^\r\n]+") do
		if not line:match("^%s*#") and line:match("%.lua%s*$") then
			out[#out + 1] = (line:gsub("^%s+", ""):gsub("%s+$", ""):gsub("\\", "/"))
		end
	end
	return out
end

-- The header: from line 1 to the first bare "--" line (or the first non-comment line).
-- A field starts "-- Key: value"; lines "--   more" continue it.
local function parseHeader(text)
	local h, last = {}, nil
	for line in (text .. "\n"):gmatch("([^\n]*)\n") do
		line = line:gsub("\r$", "")
		if line == "--" or not line:match("^%-%-") then break end
		local key, val = line:match("^%-%- (%u[%w]*):%s*(.*)$")
		if key and not h[key] then
			h[key], last = val, key
		elseif last and line:match("^%-%-%s%s+%S") then
			h[last] = h[last] .. " " .. line:match("^%-%-%s+(.*)$")
		end
	end
	return h
end

-- the W.Module("Name", { "Dep", ... }) declaration (comment lines are skipped)
local function parseModule(text)
	for line in text:gmatch("[^\n]+") do
		if not line:match("^%s*%-%-") then
			local name, rest = line:match('W%.Module%(%s*"([^"]+)"%s*(.*)')
			if name then
				local deps = {}
				local braces = rest:match("{(.-)}")
				if braces then for d in braces:gmatch('"([^"]+)"') do deps[#deps + 1] = d end end
				return name, deps
			end
		end
	end
end

local function countLines(text)
	local _, n = text:gsub("\n", "")
	if #text > 0 and text:sub(-1) ~= "\n" then n = n + 1 end
	return n
end

function M.modules(root)
	local mods = {}
	for i, file in ipairs(tocFiles(root)) do
		local text = readFile(root .. "/Wuber/" .. file) or ""
		local name, deps = parseModule(text)
		local h = parseHeader(text)
		local test = h.Test and h.Test:match("^(%S+)")
		local tf = test and readFile(root .. "/" .. test)
		mods[i] = { file = file, name = name or "?", deps = deps or {}, h = h, lines = countLines(text),
			folder = file:match("^(.*)/[^/]*$") or ".", test = test, testExists = tf ~= nil }
	end
	return mods
end

local function clean(s, none)
	if not s or s == "" then return none or "-" end
	return s
end

function M.build(root)
	local mods = M.modules(root)
	local out = {}
	local function add(s) out[#out + 1] = s end

	local intro = readFile(root .. "/tools/architecture-intro.md")
	if intro then add((intro:gsub("%s+$", ""))) add("") end

	add("<!-- BEGIN GENERATED by tools/map.lua: do not edit; edit the module headers and rerun it -->")
	add("")
	add("## Generated map (" .. #mods .. " modules, in load order)")
	add("")
	add("### Folders")
	add("")
	add("| Folder | Modules | Lines |")
	add("|---|---|---|")
	local folders, forder, total = {}, {}, 0
	for _, m in ipairs(mods) do
		local f = folders[m.folder]
		if not f then f = { n = 0, lines = 0 } folders[m.folder] = f forder[#forder + 1] = m.folder end
		f.n, f.lines, total = f.n + 1, f.lines + m.lines, total + m.lines
	end
	for _, name in ipairs(forder) do
		add(("| `Wuber/%s/` | %d | %d |"):format(name, folders[name].n, folders[name].lines))
	end
	add(("| total | %d | %d |"):format(#mods, total))
	add("")
	add("### Modules in load order")
	add("")
	add("Per module: Uses = hard dependencies (declared in `W.Module`, must load earlier); Later = modules it calls")
	add("at run time through `W.Mod` handles (they load after it). Events: `On X` = game event, `Listen X` = Wuber bus")
	add("event, `login` = `W.OnLogin`, `fires X` = `W.Fire`, `sets A.b` = fills a hook slot in another module.")
	add("")
	for i, m in ipairs(mods) do
		local h = m.h
		add(("#### %d. %s"):format(i, m.name))
		add(("`Wuber/%s`, %d lines. %s"):format(m.file, m.lines, clean(h.Purpose)))
		add("")
		add("- API: " .. clean(h.API))
		add("- Uses: " .. (#m.deps > 0 and table.concat(m.deps, ", ") or "(none)") .. "; Later: " .. clean(h.Later, "(none)"))
		add("- Events: " .. clean(h.Events, "(none)"))
		add("- Test: " .. (m.test and ("`" .. m.test .. "`" .. (m.testExists and "" or " (not written yet)")) or "(none)")
			.. (h.Standalone and ("; standalone: " .. h.Standalone) or ""))
		add("")
	end
	add("<!-- END GENERATED -->")
	return table.concat(out, "\n") .. "\n"
end

if ... == "--lib" then return M end

local script = (arg and arg[0] or "tools/map.lua"):gsub("\\", "/")
local root = (script:match("^(.*)/tools/[^/]*$")) or (script:match("^tools/[^/]*$") and ".") or "."
local mode
for _, a in ipairs(arg or {}) do if a:match("^%-%-") then mode = a end end
local text = M.build(root)
if mode == "--write" then
	local f = assert(io.open(root .. "/ARCHITECTURE.md", "wb"))
	f:write(text) f:close()
elseif mode == "--check" then
	if readFile(root .. "/ARCHITECTURE.md") ~= text then
		io.stderr:write("ARCHITECTURE.md is out of date: run lua5.1 tools/map.lua --write\n")
		os.exit(1)
	end
else
	io.write(text)
end
