-- tools/rec/probe-labels.lua: Wuber's real label strings for the probe (job 2893, Fable item 4).
--
--   lua5.1 tools/layout-check.lua --collect-labels <strings.lua> [--config ...]     1. every string the layout sweep draws, with its font, size and box
--   lua5.1 tools/rec/probe-labels.lua data <strings.lua> <labels.lua> [--scales 1,1.15,1.5]
--        2. the probe's list: P.LABELS = { hash, scales, rows = { text, font, path, size, box, maxLines, wrap, raw } }, as a Lua chunk
--           that the probe's generator (WuberProbe tools/gen-data.lua) appends to Data.lua. 'raw' is the font's own advance width (no ratio),
--           'hash' is tests/lib/probe_learn.lua L.hash over the words, so a later run says "N of M current strings unmeasured".
--   lua5.1 tools/rec/probe-labels.lua derive <strings.lua> <fixture.lua> --keep <text> ... [--cut <text> ...] [--note <words>]
--        3. a DERIVED fixture (source = "derived", never "game": the evidence ledger does not count it as measured): the rows whose text is in
--           --keep, each marked "not cut" at every scale (what the game's own Auto check saw, 2.4.3 run 3: the screens visited, no cut flagged),
--           the rows whose text is in --cut marked cut. Used by tests/r55/probe_labels_test.lua for the B10 proof.
--   lua5.1 tools/rec/probe-labels.lua --help
-- A real fixture comes from the probe's saved data instead: tools/rec/probe-import.lua writes fx.labels from the 'labels' probe.
local here = (debug.getinfo(1, "S").source:gsub("^@", ""):gsub("\\", "/"):match("^(.*)/[^/]*$")) or "."
local root = here .. "/../.."
local PL = dofile(root .. "/tests/lib/probe_learn.lua")
local M = {}

local WUBER_FONTS = "Interface\\AddOns\\Wuber\\Media\\fonts\\"
function M.fontPath(base)
	base = tostring(base):lower()
	if base:find("^inter") then return WUBER_FONTS .. base:gsub("^inter", "Inter") end
	if base == "frizqt__.ttf" then return "Fonts\\FRIZQT__.TTF" end
	if base == "arialn.ttf" then return "Fonts\\ARIALN.TTF" end
	return WUBER_FONTS .. base
end

local function q(s) return (("%q"):format(s):gsub("\\\n", "\\n")) end
local function num(n) return (("%.4f"):format(n):gsub("0+$", ""):gsub("%.$", "")) end

-- raw advance widths of a row's text (the font's own, unrounded, no ratio)
local function rawWidth(TL, row)
	local ok, w = pcall(TL.width, M.fontPath(row.font), row.size, row.text)
	return ok and w or nil
end

function M.rowsOf(path)
	local chunk, err = loadfile(path)
	if not chunk then return nil, err end
	local rows = chunk()
	if type(rows) ~= "table" then return nil, path .. " did not return a table" end
	return rows
end

function M.withRaw(rows)
	local TL = dofile(root .. "/tools/preview/textlayout.lua")
	TL.RAW, TL.PX, TL.SNAP, TL.SIZE_SNAP = true, nil, nil, nil
	for _, r in ipairs(rows) do r.raw = rawWidth(TL, r) r.path = M.fontPath(r.font) end
	return rows
end

function M.hashOf(rows)
	local words, seen = {}, {}
	for _, r in ipairs(rows) do if not seen[r.text] then seen[r.text] = true words[#words + 1] = r.text end end
	return PL.hash(words), #words
end

local function writeRows(fh, rows, extra)
	for _, r in ipairs(rows) do
		fh:write(("\t\t{ text = %s, font = %s, path = %s, size = %s, box = %s, maxLines = %s, wrap = %s, raw = %s%s },\n"):format(q(r.text), q(r.font), q(r.path or M.fontPath(r.font)),
			tostring(r.size), num(r.box), tostring(r.maxLines or 0), tostring(r.wrap ~= false), r.raw and num(r.raw) or "nil", extra and extra(r) or ""))
	end
end

function M.data(inPath, outPath, scales)
	local rows, err = M.rowsOf(inPath)
	if not rows then return nil, err end
	M.withRaw(rows)
	local hash, nwords = M.hashOf(rows)
	local fh = assert(io.open(outPath, "wb"))
	fh:write("-- GENERATED by tools/rec/probe-labels.lua from the layout sweep (layout-check --collect-labels). Do not edit.\n")
	fh:write(("P.LABELS = {\n\thash = %q, words = %d, scales = { %s },\n\trows = {\n"):format(hash, nwords, table.concat(scales, ", ")))
	writeRows(fh, rows)
	fh:write("\t},\n}\n")
	fh:close()
	return #rows, hash, nwords
end

-- fixture rows for the strings kept (a set of exact texts): trunc false at every scale, true for the texts in cut
function M.derive(inPath, outPath, keep, cut, note, scales)
	local rows, err = M.rowsOf(inPath)
	if not rows then return nil, err end
	M.withRaw(rows)
	local keepSet, cutSet = {}, {}
	for _, t in ipairs(keep) do keepSet[t] = true end
	for _, t in ipairs(cut) do cutSet[t] = true end
	local out = {}
	for _, r in ipairs(rows) do if keepSet[r.text] or cutSet[r.text] then out[#out + 1] = r end end
	local hash, nwords = M.hashOf(rows)
	local fh = assert(io.open(outPath, "wb"))
	fh:write("-- DERIVED fixture (job 2893): built from the 2.4.3 run 3 numbers, NOT a probe run. tools/rec/probe-labels.lua derive wrote it.\n")
	fh:write("-- Evidence: the Lab Auto check visited every screen of the layout sweep in the real game (build 1.60.1) and flagged no cut on the strings kept here\n")
	fh:write("-- (lab-latest.txt, REPORT-243-RUN3.md item 11); it was run at ONE setting, so every scale carries the same answer. source = \"derived\":\n")
	fh:write("-- the evidence ledger never counts it as measured. A real probe run (labels probe, game-probe-<id>.lua) replaces it.\n")
	fh:write(("return {\n\tformat = 1, kind = \"probe\", source = \"derived\", id = \"run3-labels\", build = \"71139\", note = %s,\n"):format(q(note or "derived from the run 3 Auto check")))
	fh:write(("\tlabels = {\n\t\thash = %q, words = %d, scales = { %s }, caps = { GetStringWidth = true, GetUnboundedStringWidth = true, IsTruncated = true, GetNumLines = true },\n\t\trows = {\n"):format(hash, nwords, table.concat(scales, ", ")))
	local n = #scales
	writeRows(fh, out, function(r)
		local v = cutSet[r.text] and "true" or "false"
		local t = {}
		for i = 1, n do t[i] = v end
		return (", trunc = { %s }"):format(table.concat(t, ", "))
	end)
	fh:write("\t\t},\n\t},\n}\n")
	fh:close()
	return #out, hash, nwords
end

local function main(argv)
	local cmd = argv[1]
	if not cmd or cmd == "--help" or cmd == "-h" then
		print("usage: probe-labels.lua data <strings.lua> <labels.lua> [--scales 1,1.15,1.5]\n       probe-labels.lua derive <strings.lua> <fixture.lua> --keep <text> ... [--cut <text> ...] [--note <words>]\n(see the header of this file)")
		return 0
	end
	local scales, keep, cut, note = { "1", "1.15", "1.5" }, {}, {}, nil
	local i, mode = 4, nil
	while argv[i] do
		local a = argv[i]
		if a == "--scales" then scales = {} for s in (argv[i + 1] or ""):gmatch("[^,]+") do scales[#scales + 1] = s end i = i + 1 mode = nil
		elseif a == "--keep" then mode = keep
		elseif a == "--cut" then mode = cut
		elseif a == "--note" then note = argv[i + 1] i = i + 1 mode = nil
		elseif mode then mode[#mode + 1] = a
		else print("unknown argument: " .. a) return 2 end
		i = i + 1
	end
	if not argv[2] or not argv[3] then print("need an input and an output file") return 2 end
	local n, hash, words
	if cmd == "data" then n, hash, words = M.data(argv[2], argv[3], scales)
	elseif cmd == "derive" then n, hash, words = M.derive(argv[2], argv[3], keep, cut, note, scales)
	else print("unknown command: " .. cmd) return 2 end
	if not n then print(tostring(hash)) return 1 end
	print(("%s: %d rows, hash %s (%d words)"):format(argv[3], n, tostring(hash), words))
	return 0
end
M.main = main

if (...) == "--lib" then return M end
os.exit(main({ ... }))
