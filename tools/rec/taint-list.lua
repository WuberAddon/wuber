-- tools/rec/taint-list.lua (job 2908, Fable item 8): the list of Blizzard globals and frame fields Wuber touches, for the WuberProbe sweep.
--
--   lua5.1 tools/rec/taint-list.lua [--root <repo>] [--out <file>]     writes the lab's WuberProbe/TaintList.lua (plain data); no --out: prints the counts
--   local TL = loadfile("tools/rec/taint-list.lua")("--lib")           TL.scan(sources, allow) -> { globals = { name }, fields = { { frame, field } } }; TL.render(list) -> text
--
-- Read only: it reads the Wuber files named in Wuber/Wuber.toc and tests/fakegame/taint-allow.lua and names:
--   * every game global the allow list knows (tables, globals, fields' frame, parents),
--   * every name that looks like a game window (<Something>Frame, not Wuber*) or a game API table (C_<Name>) used in the code,
--   * a short fixed seed of the game's own roots and tables Wuber writes into or hangs frames under,
--   * for each such window or table, every field the code reads or writes with a dot (Name.field; a colon method call is not a field).
-- The probe's sweep (issecurevariable) answers, per name, whether the game's own value is still secure (untainted). tools/rec/taint-compare.lua puts the answers
-- next to taint-allow.lua. Only names, never values.
local TL = {}

TL.SEED = { "UIParent", "WorldFrame", "Minimap", "GameTooltip", "UISpecialFrames", "SlashCmdList", "StaticPopupDialogs", "DEFAULT_CHAT_FRAME",
	"TradeFrame", "WorldMapFrame", "TaxiFrame", "StaticPopup1", "ChatFrame1", "PlayerFrame", "TargetFrame" }

local function sortedKeys(t) local o = {} for k in pairs(t) do o[#o + 1] = k end table.sort(o) return o end

function TL.scan(sources, allow)
	local names, seen = {}, {}
	local function name(n) if type(n) == "string" and n ~= "" and not n:find("^Wuber") and not seen[n] then seen[n] = true names[#names + 1] = n end end
	for _, n in ipairs(TL.SEED) do name(n) end
	allow = allow or {}
	for n in pairs(allow.tables or {}) do name(n) end
	for n in pairs(allow.globals or {}) do name(n) end
	for n in pairs(allow.parents or {}) do name(n) end
	for k in pairs(allow.fields or {}) do name((tostring(k):match("^([^.]+)"))) end
	for _, src in ipairs(sources) do
		local code = src:gsub("%-%-%[%[.-%]%]", ""):gsub("%-%-[^\n]*", "")
		for n in code:gmatch("%f[%w_](%u[%w]*Frame%d*)%f[^%w_]") do name(n) end
		for n in code:gmatch("%f[%w_](C_%u[%w]*)%f[^%w_]") do name(n) end
	end
	local known = {}
	for _, n in ipairs(names) do known[n] = true end
	local fields, fseen = {}, {}
	for _, src in ipairs(sources) do
		local code = src:gsub("%-%-%[%[.-%]%]", ""):gsub("%-%-[^\n]*", ""):gsub('"[^"\n]*"', '""')
		for obj, field in code:gmatch("%f[%w_]([%a_][%w_]*)%.([%a_][%w_]*)") do
			if known[obj] and not fseen[obj .. "." .. field] then fseen[obj .. "." .. field] = true fields[#fields + 1] = { obj, field } end
		end
	end
	for k in pairs(allow.fields or {}) do
		local o, f = tostring(k):match("^([^.]+)%.(.+)$")
		if o and not fseen[k] then fseen[k] = true fields[#fields + 1] = { o, f } end
	end
	table.sort(names)
	table.sort(fields, function(a, b) if a[1] ~= b[1] then return a[1] < b[1] end return a[2] < b[2] end)
	return { globals = names, fields = fields }
end

function TL.render(list)
	local o = { "-- GENERATED by tools/rec/taint-list.lua in the Wuber repo (lua5.1 tools/rec/taint-list.lua --out <this file>): the Blizzard globals and frame",
		"-- fields Wuber touches. Plain data (names only). Do not edit.", "local _, P = ...", "if type(P) ~= \"table\" then return end", "P.TAINT = {", "\tglobals = {" }
	for _, n in ipairs(list.globals) do o[#o + 1] = ("\t\t%q,"):format(n) end
	o[#o + 1] = "\t},"
	o[#o + 1] = "\tfields = {"
	for _, p in ipairs(list.fields) do o[#o + 1] = ("\t\t{ %q, %q },"):format(p[1], p[2]) end
	o[#o + 1] = "\t},"
	o[#o + 1] = "}"
	return table.concat(o, "\n") .. "\n"
end

local function readAll(path) local f = io.open(path, "rb") if not f then return nil end local s = f:read("*a") f:close() return s end

function TL.sources(root)
	local toc = readAll(root .. "/Wuber/Wuber.toc") or ""
	local out = {}
	for line in toc:gmatch("[^\r\n]+") do
		local t = line:match("^%s*(.-)%s*$")
		if t ~= "" and t:sub(1, 1) ~= "#" and t:find("%.lua$") then
			local s = readAll(root .. "/Wuber/" .. t:gsub("\\", "/"))
			if s then out[#out + 1] = s end
		end
	end
	return out
end

function TL.main(args, out)
	out = out or print
	local root, to = ".", nil
	local i = 1
	while args[i] do
		if args[i] == "--root" then root = args[i + 1] i = i + 2
		elseif args[i] == "--out" then to = args[i + 1] i = i + 2
		elseif args[i] == "--help" then out("taint-list.lua [--root <repo>] [--out <TaintList.lua>]: the Blizzard globals and fields Wuber touches (for the WuberProbe sweep)") return 0
		else out("unknown argument " .. tostring(args[i])) return 1 end
	end
	local chunk = loadfile(root .. "/tests/fakegame/taint-allow.lua")
	local allow = chunk and chunk() or {}
	local list = TL.scan(TL.sources(root), allow)
	out(("%d globals, %d fields"):format(#list.globals, #list.fields))
	if to then
		local f = assert(io.open(to, "wb")) f:write(TL.render(list)) f:close()
		out("wrote " .. to)
	end
	return 0
end

if (...) == "--lib" then return TL end
os.exit(TL.main(arg or {}))
